    #[test]
    fn update_replaces_untouched_owned_files_and_never_overwrites_edits() {
        let root = tempfile::tempdir().unwrap();
        let dir = root.path();
        create_in(dir);
        assert!(update_in(dir, true).updated.is_empty(), "a fresh project is up to date");
        // Simulate an older template: rewrite the manifest's hashes as if
        // these files had different template content.
        let mut manifest = Manifest::parse(&fs::read_to_string(dir.join(MANIFEST)).unwrap()).unwrap();
        let stale = "sha256:stale".to_string();
        manifest.version = "0.0.1".into();
        for path in ["md-bevy/src/shell.rs", "md-bevy/src/screen.rs", "game/src/lib.rs"] {
            manifest.owned.entry(path.into()).and_modify(|h| *h = stale.clone());
            manifest.seeded.entry(path.into()).and_modify(|h| *h = stale.clone());
        }
        manifest.owned.insert("md-bevy/src/gone.rs".into(), hash(b"old"));
        manifest.owned.insert("md-bevy/src/edited_gone.rs".into(), hash(b"old"));
        manifest.owned.remove("md-bevy/src/launcher.rs");
        fs::write(dir.join(MANIFEST), manifest.to_toml()).unwrap();
        // shell.rs: unmodified relative to the stale base -> updated.
        fs::write(dir.join("md-bevy/src/shell.rs"), b"stale base").unwrap();
        manifest.owned.insert("md-bevy/src/shell.rs".into(), hash(b"stale base"));
        // screen.rs: edited locally and changed upstream -> conflict.
        fs::write(dir.join("md-bevy/src/screen.rs"), b"local edit").unwrap();
        fs::write(dir.join("md-bevy/src/gone.rs"), b"old").unwrap();
        fs::write(dir.join("md-bevy/src/edited_gone.rs"), b"edited").unwrap();
        fs::remove_file(dir.join("md-bevy/src/launcher.rs")).unwrap();
        fs::write(dir.join("game/src/lib.rs"), b"my game").unwrap();
        fs::write(dir.join(MANIFEST), manifest.to_toml()).unwrap();

        let planned = update_in(dir, true);
        assert_eq!(fs::read(dir.join("md-bevy/src/shell.rs")).unwrap(), b"stale base", "dry run writes nothing");
        let done = update_in(dir, false);
        assert_eq!(planned.updated, done.updated);
        assert_eq!(done.updated, vec!["md-bevy/src/shell.rs"]);
        assert_eq!(done.added, vec!["md-bevy/src/launcher.rs"]);
        assert_eq!(done.conflicts, vec!["md-bevy/src/screen.rs"]);
        assert_eq!(done.removed, vec!["md-bevy/src/gone.rs"]);
        assert_eq!(done.kept_removed, vec!["md-bevy/src/edited_gone.rs"]);
        assert_eq!(done.seeded_changed, vec!["game/src/lib.rs"]);
        assert_eq!(fs::read(dir.join("md-bevy/src/screen.rs")).unwrap(), b"local edit");
        assert!(dir.join("md-bevy/src/screen.rs.mdx-new").is_file());
        assert!(!dir.join("md-bevy/src/gone.rs").exists());
        assert_eq!(fs::read(dir.join("game/src/lib.rs")).unwrap(), b"my game");
        assert!(dir.join(SEEDED_UPDATES).join("game/src/lib.rs").is_file());
        let after = Manifest::parse(&fs::read_to_string(dir.join(MANIFEST)).unwrap()).unwrap();
        assert_eq!(after.version, version());
        // The next update has nothing new to say about the seeded file, and
        // the unresolved edit is still not overwritten.
        let again = update_in(dir, false);
        assert!(again.seeded_changed.is_empty() && again.updated.is_empty(), "{again:?}");
        assert_eq!(fs::read(dir.join("md-bevy/src/screen.rs")).unwrap(), b"local edit");
    }

