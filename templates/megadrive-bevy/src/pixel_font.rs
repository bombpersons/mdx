fn glyph(c: char) -> &'static [&'static str; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .or_else(|| GLYPHS.iter().find(|(g, _)| *g == '?'))
        .map(|(_, rows)| rows)
        .unwrap()
}

/// Render `text` as a white-on-transparent image, `ADVANCE` pixels per character.
pub fn text_image(text: &str) -> Image {
    let width = (text.chars().count() as u32 * ADVANCE).max(1);
    let mut data = vec![0u8; (width * HEIGHT * 4) as usize];
    for (index, c) in text.chars().enumerate() {
        for (y, row) in glyph(c).iter().enumerate() {
            for (x, pixel) in row.bytes().enumerate() {
                if pixel == b'#' {
                    let at = ((y as u32 * width + index as u32 * ADVANCE + x as u32) * 4) as usize;
                    data[at..at + 4].copy_from_slice(&[255; 4]);
                }
            }
        }
    }
    Image::new(
        Extent3d { width, height: HEIGHT, depth_or_array_layers: 1 },
        TextureDimension::D2,
        data,
        TextureFormat::Rgba8UnormSrgb,
        RenderAssetUsages::default(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_by_seven_and_text_is_sized_by_advance() {
        for (c, rows) in GLYPHS {
            assert!(rows.iter().all(|row| row.len() == 5), "{c}");
        }
        let image = text_image("Ab?");
        assert_eq!((image.width(), image.height()), (3 * ADVANCE, HEIGHT));
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('~'), glyph('?'));
    }
}
